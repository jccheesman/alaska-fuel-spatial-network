#!/usr/bin/env python3
"""Stage 08 — the inventory ledger: ONE tracked workbook that answers, per release, what a human
approved, what a rule changed, what is still open. Generated from the CSVs on every run;
never edit it by hand (a hand edit is invisible to the pipeline and lost on the next run).

Tabs
    README              what each tab is and which CSV it comes from
    Summary             counts per category + qc_status of the published table
    Approved by owner   corrections.csv rows the owner decided one by one (status approved,
                        no rule guard)
    Applied by rule     approved rows that came from an owner-stated rule (decided_in names the
                        rule; exclusions guarded old_value=column=value)
    Aliases             aliases.csv
    Pending             corrections.csv rows awaiting a decision
    Rejected & retired  decisions reversed or superseded (kept, never deleted)
    Excluded            records dropped this run, with their reason (excluded.csv)
    Open review queue   review_queue.csv with the decision columns — fill this tab in and hand
                        the file to record-facility-corrections

The workbook is written deterministically (fixed document + zip timestamps) so an unchanged
inventory produces a byte-identical file and the publish determinism check can cover it.

Run:  python workflows/00_inventory_qc/08_ledger.py [--release 2025]
"""
from __future__ import annotations

import argparse
import io
import re
import sys
import zipfile
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd

from .core import OUT, QC, aliases, corrections, latest_release, read_csv

DECISIONS = ["approve", "approve with my value", "reject", "remote site", "exclude", "ask publisher", "skip for now"]
EPOCH = datetime(2000, 1, 1)

README = [
    ("README", "What this workbook is"),
    ("", "Generated by workflows/00_inventory_qc/08_ledger.py from the CSVs named below. Regenerated on every run."),
    ("", "Do NOT edit any tab except 'Open review queue' (its yellow columns). Hand the file back to record-facility-corrections."),
    ("", ""),
    ("Summary", "counts per category; qc_status of outputs/00_inventory_qc/<release>/facilities_clean.csv"),
    ("Approved by owner", "inputs/inventory_qc/corrections.csv — status=approved, decided one record at a time"),
    ("Applied by rule", "inputs/inventory_qc/corrections.csv — status=approved from an owner-stated rule (decided_in names it)"),
    ("Aliases", "inputs/inventory_qc/aliases.csv — community spellings folded into one canonical name"),
    ("Pending", "inputs/inventory_qc/corrections.csv — status=pending (awaiting the owner)"),
    ("Rejected & retired", "inputs/inventory_qc/corrections.csv — status=rejected | retired (history is never deleted)"),
    ("Excluded", "outputs/00_inventory_qc/<release>/excluded.csv — records dropped this run, with reason"),
    ("Open review queue", "outputs/00_inventory_qc/<release>/review_queue.csv — open flags; fill decision / your_value / notes / reviewed_by / reviewed_on"),
    ("", ""),
    ("Last run", "outputs/00_inventory_qc/<release>/corrections_log.csv — the outcome (applied / skipped / pending / ...) per correction row this run"),
]


def _is_rule(row) -> bool:
    d = str(row.get("decided_in", ""))
    return "rule" in d.lower() or (row.get("field") == "exclude" and "=" in str(row.get("old_value", "")))


def build(label: str) -> dict[str, pd.DataFrame]:
    out = OUT / label
    corr = corrections()
    log = read_csv(out / "corrections_log.csv") if (out / "corrections_log.csv").exists() else pd.DataFrame()
    if len(log):
        corr = corr.merge(log[["record_id", "field", "old_value", "outcome"]].rename(columns={"outcome": "last_run_outcome"}),
                          on=["record_id", "field", "old_value"], how="left")
    approved = corr[corr["status"] == "approved"]
    rule = approved[approved.apply(_is_rule, axis=1)]
    owner = approved.drop(index=rule.index)
    pending = corr[corr["status"] == "pending"]
    closed = corr[corr["status"].isin(["rejected", "retired"])]
    excl = read_csv(out / "excluded.csv") if (out / "excluded.csv").exists() else pd.DataFrame()
    keep = [c for c in ("record_id", "community_name", "entity_name", "tank_farm_id", "total_capacity", "latitude", "longitude", "exclusion_reason") if c in excl.columns]
    excl = excl[keep] if len(excl) else excl
    queue = read_csv(out / "review_queue.csv") if (out / "review_queue.csv").exists() else pd.DataFrame()
    clean = read_csv(out / "facilities_clean.csv") if (out / "facilities_clean.csv").exists() else pd.DataFrame()
    al = aliases()
    rs = pd.read_csv(QC / "remote_sites.csv", dtype=str, keep_default_na=False) if (QC / "remote_sites.csv").exists() else pd.DataFrame()

    qs = clean["qc_status"].value_counts().to_dict() if "qc_status" in clean else {}
    summary = pd.DataFrame([
        ("release", label),
        ("published records", len(clean)),
        ("  qc_status = clean", qs.get("clean", 0)),
        ("  qc_status = pending_review (withheld from hubs)", qs.get("pending_review", 0)),
        ("corrections approved by owner (one by one)", len(owner)),
        ("corrections applied by an owner-stated rule", len(rule)),
        ("  of which exclusions", int((rule["field"] == "exclude").sum()) if len(rule) else 0),
        ("alias pairs", len(al)),
        ("remote sites accepted", len(rs)),
        ("corrections pending", len(pending)),
        ("corrections rejected / retired", len(closed)),
        ("records excluded this run", len(excl)),
        ("open review-queue rows", len(queue)),
        ("  records in the queue", queue["record_id"].nunique() if len(queue) else 0),
        ("approved rows NOT applied last run (skipped)", int(approved["last_run_outcome"].astype(str).str.startswith("skipped").sum()) if "last_run_outcome" in approved else 0),
    ], columns=["item", "value"])
    return {"README": pd.DataFrame(README, columns=["tab", "meaning"]), "Summary": summary,
            "Approved by owner": owner, "Applied by rule": rule, "Aliases": al, "Pending": pending,
            "Rejected & retired": closed, "Excluded": excl, "Open review queue": queue}


def write(tabs: dict[str, pd.DataFrame], path: Path) -> bool:
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Alignment, Font, PatternFill
        from openpyxl.utils import get_column_letter
        from openpyxl.worksheet.datavalidation import DataValidation
    except ImportError:
        return False
    wb = Workbook(); wb.remove(wb.active)
    hdr = Font(name="Arial", size=10, bold=True, color="FFFFFF"); fill = PatternFill("solid", fgColor="305496")
    inp = PatternFill("solid", fgColor="FFFF00"); body = Font(name="Arial", size=10)
    link = Font(name="Arial", size=10, color="0563C1", underline="single")
    widths = {"detail": 70, "evidence": 60, "reason": 24, "meaning": 110, "item": 48, "entity_name": 30, "notes": 36,
              "community_name": 18, "exclusion_reason": 70, "suggestion": 28, "your_value": 22, "decided_in": 28, "old_value": 20, "new_value": 20}
    inputs = {"decision", "your_value", "notes", "reviewed_by", "reviewed_on"}
    for name, df in tabs.items():
        ws = wb.create_sheet(name)
        cols = list(df.columns)
        for j, c in enumerate(cols, 1):
            x = ws.cell(row=1, column=j, value=c); x.font = hdr; x.fill = fill; x.alignment = Alignment(wrap_text=True)
            ws.column_dimensions[get_column_letter(j)].width = widths.get(c, 14)
        for i, row in enumerate(df.itertuples(index=False), 2):
            for j, (c, v) in enumerate(zip(cols, row), 1):
                if v is None or (isinstance(v, float) and np.isnan(v)):
                    v = None
                if c == "map" and v:
                    x = ws.cell(row=i, column=j, value=f'=HYPERLINK("{v}","map")'); x.font = link
                else:
                    x = ws.cell(row=i, column=j, value=v); x.font = body
                    x.alignment = Alignment(wrap_text=c in ("detail", "evidence", "meaning", "exclusion_reason"), vertical="top")
                if name == "Open review queue" and c in inputs:
                    x.fill = inp
        if len(df) and name == "Open review queue" and "decision" in cols:
            dcol = get_column_letter(cols.index("decision") + 1)
            dv = DataValidation(type="list", formula1='"' + ",".join(DECISIONS) + '"', allow_blank=True)
            dv.add(f"{dcol}2:{dcol}{len(df)+1}"); ws.add_data_validation(dv)
        if len(df) and name not in ("README", "Summary"):
            ws.freeze_panes = "B2"; ws.auto_filter.ref = f"A1:{get_column_letter(len(cols))}{len(df)+1}"
    wb.properties.created = EPOCH; wb.properties.modified = EPOCH; wb.properties.creator = "08_ledger.py"
    buf = io.BytesIO(); wb.save(buf)
    # deterministic zip: fixed entry timestamps so an unchanged inventory gives a byte-identical file
    src = zipfile.ZipFile(io.BytesIO(buf.getvalue()))
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as dst:
        for info in src.infolist():
            data = src.read(info.filename)
            if info.filename == "docProps/core.xml":        # openpyxl stamps 'modified' at save time
                data = re.sub(rb"<dcterms:modified([^>]*)>[^<]*</dcterms:modified>",
                              rb"<dcterms:modified\1>2000-01-01T00:00:00Z</dcterms:modified>", data)
            zi = zipfile.ZipInfo(info.filename, date_time=(1980, 1, 1, 0, 0, 0)); zi.compress_type = zipfile.ZIP_DEFLATED
            dst.writestr(zi, data)
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--release", default=None)
    a = ap.parse_args(argv)
    label = a.release or latest_release()
    tabs = build(label)
    ok = write(tabs, OUT / label / "inventory_ledger.xlsx")
    s = tabs["Summary"].set_index("item")["value"]
    print(f"release {label}: ledger -> inventory_ledger.xlsx" + ("" if ok else " NOT written (openpyxl missing)"))
    for k in ("corrections approved by owner (one by one)", "corrections applied by an owner-stated rule", "corrections pending", "open review-queue rows"):
        print(f"  {k:48s} {s[k]}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
